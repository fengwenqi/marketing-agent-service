from enum import StrEnum


class CampaignState(StrEnum):
    DRAFT = "DRAFT"
    CONTEXT_COLLECTING = "CONTEXT_COLLECTING"
    CONTEXT_BLOCKED = "CONTEXT_BLOCKED"
    CONTEXT_READY = "CONTEXT_READY"
    STRATEGY_GENERATING = "STRATEGY_GENERATING"
    STRATEGY_PENDING_CONFIRMATION = "STRATEGY_PENDING_CONFIRMATION"


class CampaignEvent(StrEnum):
    MESSAGE_RECEIVED = "MESSAGE_RECEIVED"
    CONTEXT_BLOCKED = "CONTEXT_BLOCKED"
    CONTEXT_READY = "CONTEXT_READY"
    STRATEGY_REQUESTED = "STRATEGY_REQUESTED"
    STRATEGY_CREATED = "STRATEGY_CREATED"


class GateCode(StrEnum):
    GATE_1 = "GATE_1"
    GATE_1_5 = "GATE_1_5"
    GATE_2 = "GATE_2"
    GATE_3 = "GATE_3"


class GateDecisionType(StrEnum):
    APPROVE = "APPROVE"
    REJECT = "REJECT"

